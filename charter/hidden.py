# ------------------------------------------------------------------ law API (classified in lawlang)
def law_api(k, lid) -> dict:
    def disclose_capability_use(on=True):
        if not enabled(k):
            return False
        k.w["hidden_caps"]["disclose"] = bool(on)
        k.log("powers_disclosure", None, {"on": bool(on), "law": lid}, vis="public")
        return True

    def capability_holders(name=None):
        if not enabled(k):
            return []
        hs = k.w["hidden_caps"]["holders"]
        if name is None:
            return sorted({a for v in hs.values() for a in v})
        key = NAMES.get(str(name))
        return sorted(hs.get(key, [])) if key else []

    def revoke_capability(agent, name=None):
        if not enabled(k):
            return 0
        k.agent(agent)
        hs = k.w["hidden_caps"]["holders"]
        keys = list(CAPS) if name is None else [NAMES[str(name)]] if str(name) in NAMES else []
        n = 0
        for key in keys:
            if agent in hs.get(key, []):
                hs[key].remove(agent)
                n += 1
                if key == "secret_camps" and not k.dry:            # the camp goes with the power (never in a preview: no leak)
                    a = k.agent(agent)
                    a["rights"] = [r for r in a["rights"] if not secret_right(k, r)]
        if n:
            k.log("power_revoked", None, {"agent": agent, "name": name, "count": n, "law": lid}, vis="monitor")
        return n

    return {"disclose_capability_use": disclose_capability_use, "capability_holders": capability_holders,
            "revoke_capability": revoke_capability}



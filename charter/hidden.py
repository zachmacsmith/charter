"""Hidden knowledge and hidden powers: the tiered codex, partial documentation of the law language, and nine secret actions.

Codex. Articles describe what the prompt leaves out. File articles live in charter/archive/codex/*.md (frontmatter: tier, title,
capabilities taught, false_claims); law-language articles (codex/law/*) are generated by lawdocs.py from the spec's `law_docs`
mapping. Tiers: common, uncommon, rare, legendary (never held at the start: only found through discovery events, see
grant_article) and false (plausible but wrong). At generation each Scientist holds each non-legendary article with the tier's
chance (hidden.start_prob); every other agent with that chance times hidden.non_scientist_scale. An agent reads and searches only
the articles it holds (read_archive / search_archive on "codex/..."); Scientists keep their ordinary archive and rare records.

Powers. Nine secret actions, each used through invoke {"action": <word>, "args": [...]} with a distinctive word. Each agent outside
the Board and the Fixer holds each power independently with the power's tier chance (hidden.hold_prob); holders are not told.
Holding (may use it) and knowing (has read or been told its word) are independent. A word answers only its holders: to anyone
else, as to any unknown word, invoke says "no such action" (and the attempt costs the action, like any failed action). Uses are
logged monitor-only unless a law calls disclose_capability_use(True). Laws also read capability_holders(name) and call
revoke_capability(agent, name).

Tips and discoveries. hidden.on_round_start(k) (called from Kernel.start_round) draws, per agent per round and from a stream seeded
by (seed, round): a tip (a notice that some agent holds a power, of a power's word, of a law function the prompt leaves out, or a
false rumour) and a discovery (a legendary article, via grant_article). Other event schedulers call grant_article directly.

All hidden truth is monitor-only: instance.json["hidden"], ground_truth.json["hidden"], spec_outline.md and monitor events
(power_attempt, power_use, tip, article_granted, forgery_truth, history_forged, order_set, spawn_request).
"""
